"""p143-lockfile-audit, part (b) -- ACTION DO: does the lockfile describe the SOURCE?

lockaudit.py established that each stored hash digests the signature block stored
beside it. That is internal consistency and it is NOT the claim `P21` rests on.
`P21` rests on the lockfile pinning what the server actually SERVES -- so this part
re-derives, from `server.py` alone, the three signature fields that are literal in
source, and diffs them against the lockfile:

  name         -- the decorated function's name
  annotations  -- the literal dict passed to `@mcp.tool(annotations={...})`
  description  -- the function's docstring, normalised with `inspect.cleandoc`,
                  which is exactly what the generator documents applying

🔴 **`inputSchema` is deliberately NOT re-derived, and that limit is declared rather
than papered over.** It is generated by pydantic from the `params` model at import
time; reproducing it means executing the repository, which this audit does not do.
So this probe can say the lockfile's name/annotations/description agree with source,
and it CANNOT say the same of the schema. One of the four hashed fields is
unverifiable without execution, and a reader is entitled to know which.

Parsing is done with `ast`, not regex: the decorators are multi-line calls with
nested dict literals, and a regex over them is how an instrument goes blind (cf.
`ACTION DM`).

Run: python3 -I srcagree.py <server.py> <tools.lock.json>
"""

import ast
import inspect
import json
import sys


def decorator_tool_calls(tree):
    """{func_name: (annotations_dict_or_None, docstring_or_None, lineno, n_dec_lines)}"""
    out = {}
    for node in ast.walk(tree):
        if not isinstance(node, (ast.AsyncFunctionDef, ast.FunctionDef)):
            continue
        for dec in node.decorator_list:
            # we want `@mcp.tool(...)` -- a Call whose func is an Attribute named `tool`
            if not isinstance(dec, ast.Call):
                continue
            f = dec.func
            if not (isinstance(f, ast.Attribute) and f.attr == "tool"):
                continue
            ann = None
            for kw in dec.keywords:
                if kw.arg == "annotations":
                    try:
                        ann = ast.literal_eval(kw.value)
                    except (ValueError, TypeError):
                        ann = "UNPARSEABLE"
            doc = ast.get_docstring(node, clean=False)
            n_lines = (getattr(dec, "end_lineno", dec.lineno) or dec.lineno) - dec.lineno + 1
            out[node.name] = (ann, doc, node.lineno, n_lines)
    return out


def main(argv):
    src_path, lock_path = argv[0], argv[1]
    tree = ast.parse(open(src_path, encoding="utf-8").read())
    src = decorator_tool_calls(tree)
    lock = json.load(open(lock_path, encoding="utf-8"))

    cols = ["tool", "in_source", "in_lock", "name_agree", "annot_agree",
            "desc_agree", "schema_checked", "dec_lines", "verdict"]
    print("\t".join(cols))
    names = sorted(set(src) | set(lock))
    tally = {"AGREE": 0, "DISAGREE": 0, "LOCK_ONLY": 0, "SOURCE_ONLY": 0}
    detail = []
    for n in names:
        in_s, in_l = n in src, n in lock
        if not in_l:
            tally["SOURCE_ONLY"] += 1
            print("\t".join([n, "YES", "NO", "-", "-", "-", "NO", str(src[n][3]),
                             "SOURCE_ONLY"]))
            continue
        if not in_s:
            tally["LOCK_ONLY"] += 1
            print("\t".join([n, "NO", "YES", "-", "-", "-", "NO", "-", "LOCK_ONLY"]))
            continue
        ann, doc, _lineno, ndec = src[n]
        sig = lock[n].get("signature") or {}
        name_ok = sig.get("name") == n
        lock_ann = sig.get("annotations") or {}
        # the generator dumps with exclude_none and by_alias; the literal dict in
        # source is already in wire spelling, so compare the literal pairs only.
        ann_cmp = {k: v for k, v in (ann or {}).items() if v is not None}
        lock_cmp = {k: v for k, v in lock_ann.items() if k in ann_cmp}
        ann_ok = ann_cmp == lock_cmp
        lock_desc = sig.get("description")
        src_desc = inspect.cleandoc(doc) if doc is not None else None
        desc_ok = (lock_desc == src_desc)
        ok = name_ok and ann_ok and desc_ok
        tally["AGREE" if ok else "DISAGREE"] += 1
        print("\t".join([n, "YES", "YES",
                         "YES" if name_ok else "NO",
                         "YES" if ann_ok else "NO",
                         "YES" if desc_ok else "NO",
                         "NOT_DERIVABLE_WITHOUT_EXECUTION",
                         str(ndec),
                         "AGREE" if ok else "DISAGREE"]))
        if not ann_ok:
            detail.append("ANNOT %s\n  source: %r\n  lock:   %r" % (n, ann_cmp, lock_cmp))
        if not desc_ok:
            detail.append("DESC %s\n  source: %r\n  lock:   %r"
                          % (n, (src_desc or "")[:200], (lock_desc or "")[:200]))

    print("\n# tools declared in source : %d" % len(src), file=sys.stderr)
    print("# tools in lockfile        : %d" % len(lock), file=sys.stderr)
    for k in ("AGREE", "DISAGREE", "LOCK_ONLY", "SOURCE_ONLY"):
        print("# %-12s %d" % (k, tally[k]), file=sys.stderr)
    multi = [n for n in src if src[n][3] > 1]
    print("# decorators spanning MORE THAN ONE LINE: %d of %d  <- the shape ACTION DM "
          "says the surface gate cannot see" % (len(multi), len(src)), file=sys.stderr)
    print("# fields verifiable from source: name, annotations, description (3 of 4)",
          file=sys.stderr)
    print("# field requiring execution    : inputSchema (1 of 4) -- NOT verified",
          file=sys.stderr)
    for d in detail:
        print("\n" + d, file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
